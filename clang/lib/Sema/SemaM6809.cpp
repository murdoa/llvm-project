namespace clang {
SemaM6809::SemaM6809(Sema &S) : SemaBase(S) {}

void SemaM6809::handleInterruptAttr(Decl *D, const ParsedAttr &AL) {
  if (!isFuncOrMethodForAttrSubject(D)) {
    Diag(D->getLocation(), diag::warn_attribute_wrong_decl_type)
        << AL << AL.isRegularKeywordAttribute() << ExpectedFunction;
    return;
  }

  if (!AL.checkExactlyNumArgs(SemaRef, 0))
    return;

  // The CPU calls a handler with nothing to pass and nowhere to return a
  // value to.
  if (hasFunctionProto(D) && getFunctionOrMethodNumParams(D) != 0) {
    Diag(D->getLocation(), diag::warn_interrupt_signal_attribute_invalid)
        << /*M6809*/ 4 << /*interrupt*/ 0 << 0;
    return;
  }
  if (!getFunctionOrMethodResultType(D)->isVoidType()) {
    Diag(D->getLocation(), diag::warn_interrupt_signal_attribute_invalid)
        << /*M6809*/ 4 << /*interrupt*/ 0 << 1;
    return;
  }

  handleSimpleAttribute<M6809InterruptAttr>(*this, D, AL);
}
} // namespace clang
