#ifndef LLVM_LIB_TARGET_M6800_M6800SUBTARGET_H
#define LLVM_LIB_TARGET_M6800_M6800SUBTARGET_H

#include "M6800FrameLowering.h"
#include "M6800ISelLowering.h"
#include "M6800InstrInfo.h"
#include "llvm/CodeGen/SelectionDAGTargetInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include <memory>
#include <string>

#define GET_SUBTARGETINFO_HEADER
#include "M6800GenSubtargetInfo.inc"

namespace llvm {

class StringRef;
class TargetMachine;

class M6800Subtarget : public M6800GenSubtargetInfo {
  virtual void anchor();

  M6800InstrInfo InstrInfo;
  M6800FrameLowering FrameLowering;
  M6800TargetLowering TLInfo;
  std::unique_ptr<const SelectionDAGTargetInfo> TSInfo;

public:
  M6800Subtarget(const Triple &TT, const std::string &CPU,
                 const std::string &FS, const TargetMachine &TM);
  ~M6800Subtarget() override;

  /// Generated by TableGen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  const M6800InstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const M6800FrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const M6800TargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }
  const M6800RegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }
  const SelectionDAGTargetInfo *getSelectionDAGInfo() const override;

private:
  M6800Subtarget &initializeSubtargetDependencies(StringRef CPU, StringRef FS);
};

} // namespace llvm

#endif // LLVM_LIB_TARGET_M6800_M6800SUBTARGET_H
