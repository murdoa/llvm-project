#ifndef LLVM_LIB_TARGET_M6809_M6809SUBTARGET_H
#define LLVM_LIB_TARGET_M6809_M6809SUBTARGET_H

#include "M6809FrameLowering.h"
#include "M6809ISelLowering.h"
#include "M6809InstrInfo.h"
#include "llvm/CodeGen/SelectionDAGTargetInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include <memory>
#include <string>

#define GET_SUBTARGETINFO_HEADER
#include "M6809GenSubtargetInfo.inc"

namespace llvm {

class StringRef;
class TargetMachine;

class M6809Subtarget : public M6809GenSubtargetInfo {
  virtual void anchor();

  // Set by ParseSubtargetFeatures. It must come before the members below,
  // which are built from it.
  bool Has6309 = false;

  M6809InstrInfo InstrInfo;
  M6809FrameLowering FrameLowering;
  M6809TargetLowering TLInfo;
  std::unique_ptr<const SelectionDAGTargetInfo> TSInfo;

public:
  M6809Subtarget(const Triple &TT, const std::string &CPU,
                 const std::string &FS, const TargetMachine &TM);
  ~M6809Subtarget() override;

  /// Generated by TableGen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  bool has6309() const { return Has6309; }

  const M6809InstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const M6809FrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const M6809TargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }
  const M6809RegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }
  const SelectionDAGTargetInfo *getSelectionDAGInfo() const override;

private:
  M6809Subtarget &initializeSubtargetDependencies(StringRef CPU, StringRef FS);
};

} // namespace llvm

#endif // LLVM_LIB_TARGET_M6809_M6809SUBTARGET_H
